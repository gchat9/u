/*
 * sodium_lite.c -- the part of libsodium that mssh uses, small and portable;
 * see sodium.h.  Plain C99 with 32- and 64-bit integers only (no 128-bit
 * types, no assembly, no tables beyond the SHA-2 constants), so it builds the
 * same on every architecture of this repository.
 *
 *   SHA-256, SHA-512, ChaCha20: straight from their definitions.
 *   Poly1305: 26-bit limbs, after Andrew Moon's poly1305-donna (public domain).
 *   X25519, Ed25519: after TweetNaCl (Bernstein, Janssen, Lange, Schwabe,
 *     Wilcox-O'Hearn; public domain): field elements are 16 limbs of 16 bits
 *     in int64_t, the group arithmetic is the unified addition formula, and
 *     the scalar multiplications are plain constant-time ladders.  Slower than
 *     libsodium's (a signature takes a millisecond or two) and about a
 *     fiftieth of the size: no precomputed tables.
 *
 * Differences from libsodium: a public key whose encoding is not canonical
 * (a y coordinate of p or more) is accepted when it decodes to a valid point,
 * where libsodium refuses it.  Small-order public keys and R are refused, as
 * libsodium refuses them; the S of a signature must be below L, as in RFC
 * 8032; and the secret-dependent code is constant time but not hardened
 * beyond that.
 *
 * The constant tables are generated by gen_constants.py.
 * randombytes_buf() is in randombytes.c, which cannot share a file with libc headers.
 * tests: test.py, which compares everything with libsodium.
 */
#include <string.h>
#include "sodium.h"

typedef uint8_t  u8;
typedef uint32_t u32;
typedef uint64_t u64;
typedef int64_t  i64;
#define FOR(i, n) for (i = 0; i < (n); ++i)

static u32 ld32le(const u8 *p) { return p[0] | (u32)p[1] << 8 | (u32)p[2] << 16 | (u32)p[3] << 24; }
static void st32le(u8 *p, u32 v) { p[0] = (u8)v; p[1] = (u8)(v >> 8); p[2] = (u8)(v >> 16); p[3] = (u8)(v >> 24); }
static u32 ld32be(const u8 *p) { return (u32)p[0] << 24 | (u32)p[1] << 16 | (u32)p[2] << 8 | p[3]; }
static void st32be(u8 *p, u32 v) { p[0] = (u8)(v >> 24); p[1] = (u8)(v >> 16); p[2] = (u8)(v >> 8); p[3] = (u8)v; }
static u64 ld64be(const u8 *p) { return (u64)ld32be(p) << 32 | ld32be(p + 4); }
static void st64be(u8 *p, u64 v) { st32be(p, (u32)(v >> 32)); st32be(p + 4, (u32)v); }

/* ── misc ───────────────────────────────────────────────────────────────── */

int sodium_init(void) { return 0; }

void sodium_memzero(void *p, size_t n) { volatile u8 *v = p; while (n--) *v++ = 0; }

int sodium_memcmp(const void *b1, const void *b2, size_t n) {
    const volatile u8 *a = b1, *b = b2;
    u32 d = 0;
    while (n--) d |= *a++ ^ *b++;
    return (int)((1 & ((d - 1) >> 8)) - 1);
}

